/* 11d. LTE turbo decoder + CRC-24A — the PDSCH transport-block primitive.
 *
 * The shared/downlink data channel (PDSCH) that carries a SIB is protected by
 * the rate-1/3 turbo code of 36.212 5.1.3.2: two 8-state recursive systematic
 * convolutional constituents joined by a QPP interleaver, the pair rate-matched
 * (5.1.4.1) into the E soft bits actually transmitted. Nothing here is about a
 * subscriber — a SIB1 transport block is the cell's own broadcast identity.
 *
 * The chain, receive side:
 *   E descrambled LLRs (>0 favours bit 0)
 *     -> turbo rate de-match  (circular-buffer inverse, sub-block deinterleave)
 *     -> iterative max-log-MAP BCJR between the two constituents
 *     -> K hard bits -> CRC-24A (D^24+D^23+D^18+D^17+D^14+D^11+D^10+D^7+D^6+
 *        D^5+D^4+D^3+D+1). CRC pass => the K-24 payload bits.
 *
 * QPP parameters f1/f2 come from the full 36.212 Table 5.1.3-3 embedded below
 * (generated by proto/qpp.py, the single source shared with the numpy twin).
 * The readable statement of the whole thing is atkdsp.reference.lte_turbo_* /
 * lte_crc24a; tests/test_cross_check.py holds the C to it.
 *
 * Turbo decode is NOT a per-sample hot path (a SIB arrives every 80 ms and its
 * transport block is a few hundred bits), so — unlike the streaming kernels —
 * this call allocates its scratch. It frees everything before it returns. */
#include "internal.h"

